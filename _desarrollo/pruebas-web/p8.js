const {chromium} = require('playwright');
const {SHOTS, nuevaPagina, preparar} = require('./comun');
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({viewport: {width: 1366, height: 860}});
  const errs = [];
  const page = await nuevaPagina(ctx, errs, 'P');
  await preparar(page);
  await page.click('.mp-tarjeta[data-id=practica]');
  await page.click('text=¡A combatir!');
  await page.waitForSelector('.preview');
  await page.click('.botones-cambio .btn-cambio >> nth=5');
  await page.waitForSelector('.btn-movimiento');
  await page.click('.btn-movimiento >> nth=0');
  await page.waitForTimeout(2500);
  await page.screenshot({path: SHOTS + 'es-combate.png'});
  await page.goto('http://127.0.0.1:8080/index.html');
  await page.click('.mp-tarjeta[data-id=equipos]');
  await page.click('.slot >> nth=5');
  await page.click('.set-sprite');
  await page.fill('.buscador', 'lapras');
  await page.screenshot({path: SHOTS + 'es-selector.png'});
  await page.keyboard.press('Escape');
  await page.click('.btn-mov >> nth=3');
  await page.fill('.buscador', 'pas');
  await page.screenshot({path: SHOTS + 'es-movs.png'});
  console.log(errs);
  await browser.close();
})();
