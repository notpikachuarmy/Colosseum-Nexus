import './load-datos-node';
import {buildMod} from '../../_codigo-fuente/mod';
import {claveEspecie, validarEquipo} from '../../_codigo-fuente/equipos';
buildMod();
let fails = 0;
const ok = (n: string, c: boolean) => { console.log((c ? 'OK  ' : 'FAIL') + ' ' + n); if (!c) fails++; };
const mismo = (a: string, b: string) => claveEspecie(a) === claveEspecie(b);
ok('Diglett ≠ Diglett-Alola', !mismo('Diglett', 'Diglett-Alola'));
ok('Diglett ≠ Diglett-Custom', !mismo('Diglett', 'Diglett-Custom'));
ok('Diglett-Custom ≠ Diglett-Alola', !mismo('Diglett-Custom', 'Diglett-Alola'));
ok('Lapras ≠ Lapras-Custom', !mismo('Lapras', 'Lapras-Custom'));
ok('Meowth-Galar ≠ Meowth-Alola', !mismo('Meowth-Galar', 'Meowth-Alola'));
ok('Tauros-Paldea-Combat = Tauros-Paldea-Blaze', mismo('Tauros-Paldea-Combat', 'Tauros-Paldea-Blaze'));
ok('Rotom = Rotom-Wash', mismo('Rotom', 'Rotom-Wash'));
ok('Railspike ≠ Railspike-Ballesta', !mismo('Railspike', 'Railspike-Ballesta'));
ok('Lapras = Lapras', mismo('Lapras', 'Lapras'));
console.log(claveEspecie('Diglett-Custom'), claveEspecie('Diglett-Alola'), claveEspecie('Metagross-Custom'));
const set = (species: string, moves: string[]) => ({name: '', species, item: '', ability: '', moves, nature: 'Hardy', evs: {}, ivs: {}, level: 100, gender: '', shiny: false, teraType: 'Normal'});
const errs = validarEquipo({id: 'x', nombre: 'x', formato: 'singles', sets: [set('Diglett', ['Dig']), set('Diglett-Alola', ['Dig']), set('Diglett-Custom', ['Shadow Claw']), set('Lapras', ['Surf']), set('Lapras-Custom', ['Surf'])]} as any);
ok('Equipo con las 3 Diglett y 2 Lapras es válido: ' + errs.join(' | '), !errs.some(e => /especie|species/.test(e)));
const errs2 = validarEquipo({id: 'x', nombre: 'x', formato: 'singles', sets: [set('Diglett-Alola', ['Dig']), set('Diglett-Alola', ['Dig'])]} as any);
ok('Dos Diglett-Alola no se permite', errs2.some(e => /especie|species/.test(e)));
console.log(fails ? fails + ' FALLOS' : 'Todo OK');
